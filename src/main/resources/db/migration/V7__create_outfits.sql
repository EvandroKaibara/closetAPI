-- Deleting a piece removes it from its outfits instead of blocking the delete
CREATE TABLE outfits (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    sneaker_id INTEGER REFERENCES sneakers (id) ON DELETE SET NULL,
    tshirt_id  INTEGER REFERENCES tshirts (id) ON DELETE SET NULL,
    pants_id   INTEGER REFERENCES pants (id) ON DELETE SET NULL,
    hoodie_id  INTEGER REFERENCES hoodies (id) ON DELETE SET NULL,
    jacket_id  INTEGER REFERENCES jackets (id) ON DELETE SET NULL
);

CREATE TABLE outfit_accessories (
    outfit_id    INTEGER NOT NULL REFERENCES outfits (id) ON DELETE CASCADE,
    accessory_id INTEGER NOT NULL REFERENCES accessories (id) ON DELETE CASCADE,
    PRIMARY KEY (outfit_id, accessory_id)
);
